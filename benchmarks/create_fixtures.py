"""Generate authored fictional software fixtures, not a human-reviewed benchmark."""

import json
from pathlib import Path

ROOT = Path(__file__).parent
CORPUS = ROOT / "corpus"


def create():
    CORPUS.mkdir(exist_ok=True)
    questions = []
    names = [
        "Amber",
        "Birch",
        "Cedar",
        "Dahlia",
        "Elm",
        "Fir",
        "Garnet",
        "Hazel",
        "Iris",
        "Juniper",
    ]
    for i, name in enumerate(names):
        family = name.lower()
        split = "dev" if i < 5 else "heldout"
        main = f"{family}/service.md"
        ops = f"{family}/operations.md"
        timeout = 17 + i * 7
        retries = i + 2
        port = 8100 + i
        retention = 11 + i
        limit = 40 + i * 5
        facts = [
            (
                "Request timeout",
                f"The {name} request timeout is {timeout} milliseconds.",
                f"What is the {name} request timeout?",
            ),
            (
                "Retry policy",
                f"The {name} retry limit is {retries} attempts with exponential backoff.",
                f"What retry limit and backoff does {name} use?",
            ),
            (
                "Listener port",
                f"The {name} listener port is {port}.",
                f"Which listener port does {name} use?",
            ),
            (
                "Audit retention",
                f"The {name} audit retention period is {retention} days.",
                f"What is the {name} audit retention period?",
            ),
            (
                "Worker concurrency",
                f"The {name} worker concurrency limit is {limit} tasks.",
                f"What is the {name} worker concurrency limit?",
            ),
        ]
        text = f"# {name} service\n\n" + "\n\n".join(
            f"## {title}\n\n{fact}" for title, fact, _ in facts
        )
        text += "\n\n## Incident response\n\nFor incident recovery, follow [the recovery procedure](operations.md#recovery).\n"
        recovery = (
            f"Recover {name} by restoring snapshot {family}-verified and replaying its journal."
        )
        health = f"The {name} health endpoint returns healthy only after {i + 3} consecutive successful probes."
        target = CORPUS / main
        target.parent.mkdir(exist_ok=True)
        target.write_text(text)
        (CORPUS / ops).write_text(
            f"# {name} operations\n\n## Recovery\n\n{recovery}\n\n## Health\n\n{health}\n"
        )

        def question(suffix, query, groups, category, family=family, split=split):
            questions.append(
                {
                    "id": f"{family}-{suffix}",
                    "query": query,
                    "family": family,
                    "split": split,
                    "category": category,
                    "evidence_groups": groups,
                }
            )

        for number, (_, fact, query) in enumerate(facts):
            question(str(number), query, [[{"source": main, "text": fact}]], "lookup")
        question(
            "multi",
            f"What are the {name} request timeout and incident recovery procedure?",
            [[{"source": main, "text": facts[0][1]}], [{"source": ops, "text": recovery}]],
            "cross_document",
        )
        question("missing", f"qzxunsupported{family} teleportation coefficient", [], "unanswerable")
    data = {
        "schema_version": 1,
        "provenance": "Authored fictional software fixtures generated by benchmarks/create_fixtures.py",
        "review_status": "machine-validated passage labels; independent human review pending",
        "questions": questions,
    }
    (ROOT / "dataset.json").write_text(json.dumps(data, indent=2) + "\n")
    print(f"Created {len(questions)} authored questions across {len(names)} disjoint families.")


if __name__ == "__main__":
    create()
